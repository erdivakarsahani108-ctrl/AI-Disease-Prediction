"""
scripts/build_knowledge_base.py
=================================
Builds the structured knowledge-base CSVs used by the Disease Dictionary,
Medicine Information and Knowledge Graph modules:

    data/disease_dictionary.csv
    data/symptom_dictionary.csv

`data/medicine_dictionary.csv` is maintained as a hand-curated seed file
(see docs/data_sources.md - "Medicine Information") because no free,
licensed, machine-readable medicine API/dataset was available to this
project; it is NOT generated by this script.

Everything generated here is derived either directly from the real public
source files (`symptom_Description.csv`, `symptom_precaution.csv`,
`Symptom-severity.csv`) or computed from the cleaned dataset itself
(e.g. "similar diseases" via Jaccard symptom-overlap). No clinical fact is
invented.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd

from src.preprocessing.categories import get_category
from src.preprocessing.clean import (
    build_disease_symptom_pool,
    load_disease_descriptions,
    load_disease_precautions,
    load_real_disease_symptom_sets,
    load_symptom_vocabulary,
)
from src.utils.paths import DISEASE_DICTIONARY_CSV, SYMPTOM_DICTIONARY_CSV
from src.utils.text import to_display_name

VERIFICATION_DATE = date.today().isoformat()
SOURCE_NOTE = "Kaggle Disease-Symptom Prediction public dataset (symptom_Description.csv / symptom_precaution.csv)"

GENERIC_CARE_TEMPLATE = (
    "Seek professional medical evaluation if symptoms are severe, persistent "
    "(beyond a few days), rapidly worsening, or accompanied by any red-flag "
    "symptom (e.g. severe breathing difficulty, chest pain, confusion, "
    "uncontrolled bleeding). This guidance is general and not a substitute "
    "for professional diagnosis."
)


def jaccard(a: set, b: set) -> float:
    if not a or not b:
        return 0.0
    inter = len(a & b)
    union = len(a | b)
    return round(inter / union, 3) if union else 0.0


def build_disease_dictionary():
    desc_df = load_disease_descriptions()
    prec_df = load_disease_precautions()
    real_df = load_real_disease_symptom_sets()
    pool = build_disease_symptom_pool(real_df)  # disease -> sorted list of real symptoms

    prec_cols = [c for c in prec_df.columns if c.lower().startswith("precaution")]

    rows = []
    diseases = sorted(pool.keys())
    for disease in diseases:
        symptoms = set(pool.get(disease, []))

        # Similar diseases via symptom-overlap (Jaccard), purely data-driven.
        sims = []
        for other in diseases:
            if other == disease:
                continue
            score = jaccard(symptoms, set(pool.get(other, [])))
            if score > 0:
                sims.append((other, score))
        sims.sort(key=lambda x: x[1], reverse=True)
        top_similar = "; ".join(f"{d} ({s:.0%})" for d, s in sims[:3]) or "None found in current dataset"

        desc_row = desc_df[desc_df["Disease"] == disease]
        description = (
            desc_row["Description"].iloc[0]
            if not desc_row.empty
            else "Description not available in current source dataset (Future Scope: integrate a licensed medical reference API)."
        )

        prec_row = prec_df[prec_df["Disease"] == disease]
        if not prec_row.empty:
            precautions = "; ".join(
                str(prec_row[c].iloc[0]) for c in prec_cols if pd.notna(prec_row[c].iloc[0])
            )
        else:
            precautions = "Not available in current source dataset."

        common_symptoms = ", ".join(to_display_name(s) for s in sorted(symptoms)[:8])

        rows.append(
            {
                "disease": disease,
                "aliases": "",  # Future Scope: alias list requires a curated medical thesaurus/UMLS mapping
                "category": get_category(disease),
                "description": description,
                "common_symptoms": common_symptoms,
                "total_known_symptoms": len(symptoms),
                "general_precautions": precautions,
                "risk_factors": "Not available as structured data in the current dataset (Future Scope: integrate epidemiological risk-factor dataset).",
                "when_to_seek_professional_care": GENERIC_CARE_TEMPLATE,
                "similar_diseases": top_similar,
                "source": SOURCE_NOTE,
                "verification_date": VERIFICATION_DATE,
            }
        )

    out = pd.DataFrame(rows)
    DISEASE_DICTIONARY_CSV.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(DISEASE_DICTIONARY_CSV, index=False)
    print(f"Saved disease dictionary -> {DISEASE_DICTIONARY_CSV} ({len(out)} diseases)")


def build_symptom_dictionary():
    vocab_df = load_symptom_vocabulary()
    real_df = load_real_disease_symptom_sets()

    # Which diseases is each symptom associated with (real data only)?
    symptom_to_diseases: dict[str, set] = {}
    for disease, symptoms in zip(real_df["disease"], real_df["symptoms"]):
        for s in symptoms:
            symptom_to_diseases.setdefault(s, set()).add(disease)

    rows = []
    for _, r in vocab_df.iterrows():
        s = r["Symptom"]
        assoc = sorted(symptom_to_diseases.get(s, []))
        weight = int(r["severity_weight"])
        risk_band = "High" if weight >= 6 else ("Moderate" if weight >= 4 else "Low")
        rows.append(
            {
                "symptom": s,
                "display_name": to_display_name(s),
                "severity_weight": weight,
                "severity_band": risk_band,
                "associated_disease_count": len(assoc),
                "associated_diseases_sample": ", ".join(assoc[:5]),
                "source": "Symptom-severity.csv (public dataset)",
                "verification_date": VERIFICATION_DATE,
            }
        )

    out = pd.DataFrame(rows).sort_values("symptom").reset_index(drop=True)
    SYMPTOM_DICTIONARY_CSV.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(SYMPTOM_DICTIONARY_CSV, index=False)
    print(f"Saved symptom dictionary -> {SYMPTOM_DICTIONARY_CSV} ({len(out)} symptoms)")


def main():
    build_disease_dictionary()
    build_symptom_dictionary()


if __name__ == "__main__":
    main()
