"""Downloadable Health Information Report generator (PDF).

Explicitly NOT a medical diagnosis certificate - this is stated on the
report itself. Contains only information already shown in the app during
the session (no extra personal data is collected to build this report).
"""

from __future__ import annotations

from datetime import datetime
from io import BytesIO

from fpdf import FPDF
from fpdf.enums import XPos, YPos


def _mc(pdf: FPDF, h: float, text: str) -> None:
    """multi_cell wrapper that always resets the cursor to the left margin
    on the next line (fpdf2's own default leaves x at the cell's right edge,
    which eventually causes a 'not enough horizontal space' error on
    subsequent calls)."""
    pdf.multi_cell(0, h, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)


class HealthReportPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 10, "AI Health Information Report", ln=True, align="C")
        self.set_font("Helvetica", "", 9)
        self.cell(0, 6, "(Not a medical diagnosis certificate)", ln=True, align="C")
        self.ln(2)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by AI Disease Prediction Assistant", align="C")


def _clean(text: str) -> str:
    """FPDF's built-in Helvetica font is latin-1 only - strip characters
    outside that range (e.g. emoji) so PDF generation never fails."""
    return str(text).encode("latin-1", "ignore").decode("latin-1")


def generate_health_report(
    active_symptoms: list[str],
    duration_days: int | None,
    top_predictions: list[dict],
    risk: dict | None,
    disease_info: dict | None,
) -> bytes:
    pdf = HealthReportPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "", 11)

    pdf.cell(0, 8, _clean(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}"), ln=True)
    pdf.ln(2)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "1. Reported Symptoms", ln=True)
    pdf.set_font("Helvetica", "", 11)
    symptoms_text = ", ".join(s.replace("_", " ").title() for s in active_symptoms) or "None recorded"
    _mc(pdf, 7, _clean(symptoms_text))
    pdf.cell(0, 7, _clean(f"Reported duration: {duration_days} day(s)" if duration_days else "Duration: Not specified"), ln=True)
    pdf.ln(2)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "2. Top Model Predictions", ln=True)
    pdf.set_font("Helvetica", "", 11)
    if top_predictions:
        for i, p in enumerate(top_predictions, start=1):
            pdf.cell(0, 7, _clean(f"{i}. {p['disease']} - {p['confidence']*100:.1f}% model confidence"), ln=True)
    else:
        pdf.cell(0, 7, "No prediction was generated (insufficient information).", ln=True)
    _mc(pdf, 6, _clean("Note: Model confidence is not a medically validated probability."))
    pdf.ln(2)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "3. AI-Assisted Risk Indicator", ln=True)
    pdf.set_font("Helvetica", "", 11)
    if risk:
        pdf.cell(0, 7, _clean(f"{risk['band']} (heuristic score: {risk['score']})"), ln=True)
        _mc(pdf, 6, _clean(risk["disclaimer"]))
    else:
        pdf.cell(0, 7, "Not available.", ln=True)
    pdf.ln(2)

    if disease_info:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, "4. General Information About Top Predicted Disease", ln=True)
        pdf.set_font("Helvetica", "", 11)
        _mc(pdf, 6, _clean(f"Disease: {disease_info.get('disease', '')}"))
        _mc(pdf, 6, _clean(f"Category: {disease_info.get('category', '')}"))
        _mc(pdf, 6, _clean(f"Description: {disease_info.get('description', '')}"))
        _mc(pdf, 6, _clean(f"General precautions: {disease_info.get('general_precautions', '')}"))
        _mc(pdf, 6, _clean(f"Source: {disease_info.get('source', '')} (verified {disease_info.get('verification_date', '')})"))
        pdf.ln(2)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "5. Important Notices", ln=True)
    pdf.set_font("Helvetica", "", 10)
    _mc(
        pdf,
        6,
        _clean(
            "This report is generated by an AI-assisted educational tool. It is NOT "
            "a medical diagnosis certificate and must not be used as one. It does not "
            "replace professional medical evaluation. If you have serious, worsening "
            "or emergency symptoms, seek immediate professional medical care. "
            "See the Medical Disclaimer and Privacy Policy pages of this application "
            "for full details."
        ),
    )

    buf = BytesIO(pdf.output())
    return buf.getvalue()
